const normalize = (value: string) => value.replace(/\s+/g, ' ').trim();

export function translateUiText(value: string, language: AppLanguage): string {
  if (language === 'bs' || !value.trim()) return value;
  const normalized = normalize(value);
  const leadingWhitespace = value.match(/^\s*/)?.[0] ?? '';
  const trailingWhitespace = value.match(/\s*$/)?.[0] ?? '';
  const exact = BS_TO_EN[normalized];
  if (exact) return `${leadingWhitespace}${exact}${trailingWhitespace}`;
  for (const [pattern, replacement] of DYNAMIC_TRANSLATIONS) {
    const match = normalized.match(pattern);
    if (match) return `${leadingWhitespace}${replacement(...match.slice(1))}${trailingWhitespace}`;
  }
  return value;
}

const originalText = new WeakMap<Text, string>();
const renderedText = new WeakMap<Text, string>();
const originalAttributes = new WeakMap<Element, Map<string, string>>();
const renderedAttributes = new WeakMap<Element, Map<string, string>>();
const localizedAttributes = ['aria-label', 'title', 'placeholder'];

function localizeTextNode(node: Text, language: AppLanguage) {
  const current = node.data;
  const lastRendered = renderedText.get(node);
  if (!originalText.has(node) || (current !== lastRendered && current !== originalText.get(node))) {
    originalText.set(node, current);
  }
  const source = originalText.get(node) ?? current;
  const next = translateUiText(source, language);
  renderedText.set(node, next);
  if (current !== next) node.data = next;
}

function localizeElement(element: Element, language: AppLanguage) {
  let originals = originalAttributes.get(element);
  let rendered = renderedAttributes.get(element);
  if (!originals) {
    originals = new Map();
    originalAttributes.set(element, originals);
  }
  if (!rendered) {
    rendered = new Map();
    renderedAttributes.set(element, rendered);
  }
  for (const attribute of localizedAttributes) {
    const current = element.getAttribute(attribute);
    if (current === null) continue;
    if (!originals.has(attribute) || (current !== rendered.get(attribute) && current !== originals.get(attribute))) {
      originals.set(attribute, current);
    }
    const next = translateUiText(originals.get(attribute) ?? current, language);
    rendered.set(attribute, next);
    if (current !== next) element.setAttribute(attribute, next);
  }
}

function localizeTree(root: Node, language: AppLanguage) {
  if (root.nodeType === Node.TEXT_NODE) {
    localizeTextNode(root as Text, language);
    return;
  }
  if (root.nodeType !== Node.ELEMENT_NODE && root.nodeType !== Node.DOCUMENT_NODE) return;
  if (root instanceof Element) localizeElement(root, language);
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT);
  let current = walker.nextNode();
  while (current) {
    if (current.nodeType === Node.TEXT_NODE) localizeTextNode(current as Text, language);
    else localizeElement(current as Element, language);
    current = walker.nextNode();
  }
}

export function useUiLocalization(language: AppLanguage) {
  useEffect(() => {
    const root = document.getElementById('root');
    if (!root) return;
    localizeTree(root, language);
    const observer = new MutationObserver((mutations) => {
      for (const mutation of mutations) {
        if (mutation.type === 'characterData') localizeTree(mutation.target, language);
        if (mutation.type === 'attributes') localizeElement(mutation.target as Element, language);
        mutation.addedNodes.forEach((node) => localizeTree(node, language));
      }
    });
    observer.observe(root, {
      subtree: true,
      childList: true,
      characterData: true,
      attributes: true,
      attributeFilter: localizedAttributes,
    });
    return () => observer.disconnect();
  }, [language]);
}
